#!/usr/bin/env node
/* Writes js/friends/released.js: the Rätsel the children's version (main channel) may show.

   The children's version has no review function. At release time this tool asks the real app (dev channel, in a
   headless browser) which Rätsel are released by the published approvals on the puzzle-review-data branch, using the
   app's own rules: every current iteration approved at its exact (or a recorded equivalent) revision, confirmed on
   GitHub, and no open general comment. It records each released Rätsel with its exact puzzle revision, so a later code
   change to that Rätsel hides it in the children's version until it is reviewed and released again.

   Usage: node tools/release-manifest.cjs [--ledger file.json] [--allow-unapproved]
   Without --ledger it reads reviews.json from origin/puzzle-review-data (run git fetch origin puzzle-review-data first).
   Without --allow-unapproved it fails when any catalogue Rätsel is not approved: a release ships approved Rätsel only. */
const fs = require('node:fs'), path = require('node:path'), http = require('node:http'), {execFileSync} = require('node:child_process');
const root = path.resolve(__dirname, '..'), args = process.argv.slice(2), arg = name => { const i = args.indexOf(name); return i < 0 ? null : args[i + 1]; };
const {remoteServer, installRemote} = require('../tests/review-repository-support.cjs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

function ledgerSource() {
  if (arg('--ledger')) return {ledger: JSON.parse(fs.readFileSync(arg('--ledger'), 'utf8')), source: path.basename(arg('--ledger'))};
  const commit = execFileSync('git', ['rev-parse', 'origin/puzzle-review-data'], {cwd: root, encoding: 'utf8'}).trim();
  return {ledger: JSON.parse(execFileSync('git', ['show', commit + ':reviews.json'], {cwd: root, encoding: 'utf8', maxBuffer: 1 << 28})), source: 'puzzle-review-data@' + commit.slice(0, 12)};
}
const TYPES = {'.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.webp': 'image/webp', '.png': 'image/png', '.svg': 'image/svg+xml', '.woff2': 'font/woff2', '.mp3': 'audio/mpeg', '.glb': 'model/gltf-binary'};
function serve() {
  const server = http.createServer((req, res) => {
    const file = path.join(root, decodeURIComponent(new URL(req.url, 'http://x').pathname).replace(/\/$/, '/index.html'));
    if (!file.startsWith(root) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { res.writeHead(404); res.end(); return; }
    res.writeHead(200, {'Content-Type': TYPES[path.extname(file)] || 'application/octet-stream'}); fs.createReadStream(file).pipe(res);
  });
  return new Promise(resolve => server.listen(0, '127.0.0.1', () => resolve(server)));
}

(async () => {
  const {ledger, source} = ledgerSource(), server = await serve(), base = 'http://127.0.0.1:' + server.address().port;
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader']});
  try {
    const context = await browser.newContext({serviceWorkers: 'block'}), page = await context.newPage();
    await installRemote(context, remoteServer(ledger));
    await page.goto(base + '/?software=1&channel=dev');
    await page.waitForFunction(() => window.FK?.reviewRepository?.state?.phase === 'saved', null, {timeout: 120000});
    const result = await page.evaluate(() => {
      const C = FK.puzzleCatalogue, games = FK.friendsLibrary.catalogue();
      return {channel: FK.CHANNEL, games: games.map(g => ({id: g.id, title: C.puzzle(g.id).title, host: g.host, revision: C.puzzleRevision(g.id), ready: FK.puzzleReview.ready(g.id), progress: FK.puzzleReview.progress(g.id)}))};
    });
    if (result.channel !== 'dev') throw Error('The release check must run on the dev channel, got ' + result.channel);
    const released = result.games.filter(g => g.ready), open = result.games.filter(g => !g.ready);
    for (const g of result.games) console.log((g.ready ? 'released  ' : 'NOT READY ') + g.id.padEnd(22) + ' ' + g.title + (g.ready ? '' : ` (${g.progress.approved}/${g.progress.total} Aufgaben freigegeben)`));
    if (open.length && !args.includes('--allow-unapproved')) { console.error(`\n${open.length} Rätsel are not approved. Approve them in the dev version first, or pass --allow-unapproved to release without them.`); process.exitCode = 1; return; }
    if (!released.length) throw Error('No Rätsel is released; refusing to write an empty release.');
    const manifest = {source, puzzles: Object.fromEntries(released.map(g => [g.id, g.revision]))};
    fs.writeFileSync(path.join(root, 'js/friends/released.js'),
      '/* Generated by tools/release-manifest.cjs: the Rätsel the children\'s version (main channel) shows, each at its\n   exact released revision. Do not edit by hand. The dev channel ignores this file and reviews live. */\n' +
      'window.FK = window.FK || {};\nFK.RELEASED = ' + JSON.stringify(manifest, null, 1) + ';\n');
    console.log(`\nWrote js/friends/released.js: ${released.length} of ${result.games.length} Rätsel from ${source}.`);
  } finally { await browser.close(); server.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
